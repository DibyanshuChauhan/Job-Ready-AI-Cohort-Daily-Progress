import { body, validationResult } from "express-validator";

/*
=========================================================

validate()

This middleware checks
whether validation passed
or failed.

validationResult(req)

collects ALL validation errors
generated by body() validators.

=========================================================
*/

const validate = (req, res, next) => {

    /*
    Collect all validation errors
    */

    const errors = validationResult(req);

    /*
    If no errors exist

    Continue to the next middleware
    */

    if (errors.isEmpty()) {
        return next();
    }

    /*
    Validation Failed

    Send all errors
    back to the client.
    */

    res.status(400).json({
        errors: errors.array()
    });
};

/*
=========================================================

REGISTER VALIDATION

This is an array of middleware.

Express executes each middleware
one after another.

Execution Order

1. username validation

↓

2. email validation

↓

3. password validation

↓

4. validate()

=========================================================
*/

export const registerValidion = [

    /*
    body("username")

    Reads

    req.body.username
    */

    body("username")

        /*
        Check if username
        is a string.
        */

        .isString()

        /*
        Custom error message.
        */

        .withMessage("Username should be a string"),

    /*
    Validate Email
    */

    body("email")

        .isEmail()

        .withMessage("Email should be a valid email address"),

    /*
    Password Validation
    */

    body("password")

        .custom((value) => {

            /*
            Minimum Length Check
            */

            if (value.length < 6) {

                throw new Error(
                    "Password should be at least 6 characters long"
                );
            }

            /*
            Regular Expression

            (?=.*[A-Z])

            At least one uppercase letter

            (?=.*\\d)

            At least one number

            */

            const passwordRegex =
                /^(?=.*[A-Z])(?=.*\d).+$/;

            if (!passwordRegex.test(value)) {

                throw new Error(
                    "Password should contain at least one uppercase letter and one number"
                );
            }

            /*
            Validation Passed
            */

            return true;

        }),

    /*
    Final Middleware

    Checks if any validation failed.
    */

    validate
];

/*
=========================================================

FLOW

body("username")

↓

body("email")

↓

body("password")

↓

validationResult()

↓

Errors?

YES

↓

400 Response

NO

↓

next()

↓

Controller

=========================================================
*/